#!/usr/bin/env python3
"""Resolve the Minimus base image tags to digests, and write the lock file.

ADR-0010 requires pinned digests, so a build is reproducible and a tag cannot
be repointed under us. Minimus rebuilds continuously, which is most of why its
images are near zero CVE. Those two facts pull against each other: a pinned
digest is reproducible and goes stale, and a floating tag is fresh and is not
reproducible.

The resolution is to pin, and to refresh the pin deliberately. This script
re-resolves every tag and rewrites `docker/base-images.lock`. A scheduled
pipeline runs it weekly and opens a merge request when a digest moves, so the
refresh is a reviewed change rather than something that happens silently
between two builds of the same commit.

  scripts/ci/refresh_base_images.py            rewrite the lock
  scripts/ci/refresh_base_images.py --check    fail if a pin has drifted
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
LOCK = ROOT / "docker" / "base-images.lock"

REGISTRY = "reg.mini.dev"
AUTH = "https://auth.mini.dev/api/v1/registry/token"
ACCEPT = ", ".join([
    "application/vnd.oci.image.index.v1+json",
    "application/vnd.docker.distribution.manifest.list.v2+json",
    "application/vnd.oci.image.manifest.v1+json",
    "application/vnd.docker.distribution.manifest.v2+json",
])

# Versions chosen by measurement at TASK-P0-029, not by habit. See ADR-0018.
#   python 3.12  13 findings, 3 High     python 3.13  3 findings, 0 High
#   nginx  1.27  93 findings, 6 Critical nginx  1.30  0 findings
#   node   22-dev  0 findings
IMAGES = [
    ("python", "3.13", "runtime for the api and worker images"),
    ("python", "3.13-dev", "builder stage, has a shell and pip"),
    ("node", "22-dev", "builder stage for the web image"),
    ("nginx", "1.30", "runtime for the web image"),
]


def token(repo: str) -> str:
    url = f"{AUTH}?service={REGISTRY}&scope=repository:{repo}:pull"
    with urllib.request.urlopen(url, timeout=25) as response:
        return json.load(response)["token"]


def resolve(repo: str, tag: str) -> tuple[str, list[str]]:
    request = urllib.request.Request(
        f"https://{REGISTRY}/v2/{repo}/manifests/{tag}",
        headers={"Authorization": f"Bearer {token(repo)}", "Accept": ACCEPT},
    )
    with urllib.request.urlopen(request, timeout=25) as response:
        digest = response.headers.get("docker-content-digest", "")
        body = json.loads(response.read())
    platforms = sorted({
        f"{m['platform']['os']}/{m['platform']['architecture']}"
        for m in body.get("manifests", []) if "platform" in m
    })
    return digest, platforms


def render(entries: list[dict], stamp: str) -> str:
    lines = [
        "# Basic boiler Plate Doc | Grade B",
        "# Why this file exists: Pins every base image by digest, because a tag moves",
        "# and a digest does not.",
        "# Grade B here: copy it, then replace the images and their digests.",
        "# Grades: A copy into a new project as is, no edits. B copy it and swap the",
        "# names, paths or patterns named above. C leave behind, it is this project's",
        "# own content rather than scaffolding, and is not tagged.",
        "#",
        "# Base image lock. Generated by scripts/ci/refresh_base_images.py.",
        "#",
        "# ADR-0010 requires pinned digests. Minimus rebuilds continuously, which",
        "# is most of why its images are near zero CVE, so a pin goes stale by",
        "# design. A weekly pipeline re-resolves these and opens a merge request",
        "# when one moves, making the refresh a reviewed change rather than",
        "# something that happens silently between two builds of one commit.",
        "#",
        f"# Resolved: {stamp}",
        "",
    ]
    for e in entries:
        lines += [
            f"# {e['note']}",
            f"# platforms: {', '.join(e['platforms'])}",
            f"{e['repo']}:{e['tag']} {e['digest']}",
            "",
        ]
    return "\n".join(lines)


def parse(text: str) -> dict[str, str]:
    out = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            ref, digest = line.split()
            out[ref] = digest
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    entries, drift = [], []
    existing = parse(LOCK.read_text()) if LOCK.exists() else {}

    for repo, tag, note in IMAGES:
        try:
            digest, platforms = resolve(repo, tag)
        except Exception as exc:
            print(f"FAIL: could not resolve {repo}:{tag}: {exc}")
            return 2
        if not digest:
            print(f"FAIL: {repo}:{tag} returned no digest")
            return 2
        if "linux/amd64" not in platforms:
            # The deploy target is amd64. An image without it would fail at
            # runtime with exec format error, which reads like a broken binary.
            print(f"FAIL: {repo}:{tag} has no linux/amd64 manifest")
            return 2
        ref = f"{repo}:{tag}"
        was = existing.get(ref)
        if was and was != digest:
            drift.append(f"{ref}\n    was {was}\n    now {digest}")
        entries.append({"repo": repo, "tag": tag, "digest": digest,
                        "platforms": platforms, "note": note})

    if args.check:
        if drift:
            print(f"Base image drift: {len(drift)} pin(s) moved upstream\n")
            for d in drift:
                print(f"  {d}")
            print("\nRun scripts/ci/refresh_base_images.py and review the diff.")
            return 1
        print(f"OK: {len(entries)} base image pins current")
        return 0

    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
    LOCK.write_text(render(entries, stamp))
    print(f"Wrote {LOCK.relative_to(ROOT)}, {len(entries)} images")
    for d in drift:
        print(f"  moved: {d.splitlines()[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
