/**
 * Turn the Natural Earth land outline into SVG path data the map can render. FEAT-061.
 *
 * **Generated, not hand authored, and that is the whole point of this file.** The first two
 * versions of the map drew continents written out from memory, which produced shapes nobody
 * recognised: a North America with a spike where Alaska should be and a Europe in fragments. That
 * was the wrong approach rather than a bad attempt at the right one. This reads the same public
 * domain outline every mapping library uses and projects it.
 *
 * **Its dependencies are dev only, and the output is committed.** `world-atlas` and
 * `topojson-client` are not in `dependencies` and never reach a browser. What ships is a plain
 * string of path data, so the page renders a real coastline with no runtime library, no projection
 * code and no fetch. Re-run with `make world` if the crop or the resolution changes.
 *
 * **110m rather than 50m.** The backdrop's job is recognition, and a tenth of the size renders in
 * a tenth of the time. Islands below a threshold are dropped, because at this scale they are
 * single pixels of noise around the shapes a reader is actually looking at.
 */

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = require('world-atlas/land-110m.json');

/** The crop, which has to match `WorldMap.tsx`. Antarctica is out and no provider has a region. */
const NORTH = 83;
const SOUTH = -56;
const WIDTH = 1000;
const HEIGHT = Math.round((WIDTH * (NORTH - SOUTH)) / 360);

/** Square drawing units. Below this a ring is a speck, and there are hundreds of them. */
const SMALLEST_ISLAND = 6;

function project([lon, lat]) {
  return [
    ((lon + 180) / 360) * WIDTH,
    ((NORTH - lat) / (NORTH - SOUTH)) * HEIGHT,
  ];
}

/** Twice the signed area, which is all that is needed to compare a ring against a threshold. */
function areaOf(points) {
  let total = 0;
  for (let i = 0; i < points.length; i += 1) {
    const [x1, y1] = points[i];
    const [x2, y2] = points[(i + 1) % points.length];
    total += x1 * y2 - x2 * y1;
  }
  return Math.abs(total / 2);
}

// `feature` returns a FeatureCollection where the topology object is a GeometryCollection and a
// single Feature otherwise, and world-atlas has shipped both shapes across versions. Handling
// both rather than assuming one, because the wrong assumption fails at the first property access
// with a message that says nothing about topology.
const land = feature(topology, topology.objects.land);
const geometries =
  land.type === 'FeatureCollection' ? land.features.map((one) => one.geometry) : [land.geometry];
const polygons = geometries.flatMap((geometry) =>
  geometry.type === 'MultiPolygon' ? geometry.coordinates : [geometry.coordinates],
);

const rings = [];
for (const polygon of polygons) {
  for (const ring of polygon) {
    const points = ring.map(project);
    if (areaOf(points) < SMALLEST_ISLAND) continue;
    // Wholly outside the crop, which is Antarctica and a few southern islands. Kept out of the
    // file rather than drawn off canvas: invisible bytes are still bytes a reader downloads.
    if (points.every(([, y]) => y > HEIGHT) || points.every(([, y]) => y < 0)) continue;
    rings.push(points);
  }
}

// One decimal is a tenth of a drawing unit, which at any size this renders at is well under a
// pixel. Two decimals would be forty percent more bytes for a difference nothing can display.
const paths = rings.map(
  (points) =>
    `M${points.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`,
);

const out = `// GENERATED by scripts/build_world.mjs. Do not edit: run \`make world\`.
//
// The Natural Earth 110m land outline, projected equirectangular and cropped to ${String(NORTH)}N
// and ${String(SOUTH)}S, as SVG path data. Public domain, from the world-atlas package, which is a
// dev dependency: nothing here reaches the browser except this string.
//
// Generated rather than hand authored because two attempts at writing coastlines from memory
// produced shapes nobody recognised, which was the wrong approach rather than a poor attempt at
// the right one.

/** The projection this was generated with. \`WorldMap.tsx\` must draw at the same size. */
export const WORLD = {
  width: ${String(WIDTH)},
  height: ${String(HEIGHT)},
  north: ${String(NORTH)},
  south: ${String(SOUTH)},
} as const;

/** One path per landmass, largest first, islands under ${String(SMALLEST_ISLAND)} square units dropped. */
export const LAND: readonly string[] = [
${rings
  .map((points, index) => ({ points, index }))
  .sort((a, b) => areaOf(b.points) - areaOf(a.points))
  .map(({ index }) => `  '${paths[index]}',`)
  .join('\n')}
];
`;

writeFileSync(new URL('../src/components/worldPaths.ts', import.meta.url), out);
console.log(
  `wrote ${String(rings.length)} rings, ${String(Math.round(out.length / 1024))} KB, ` +
    `${String(WIDTH)}x${String(HEIGHT)}`,
);
