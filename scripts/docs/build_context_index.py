"""Generate context_index.md: every public symbol, where it lives, who calls it.

This file is load bearing. Rung two of the ADR-0013 ladder, "does it already
exist in this repository", tells an engineer or an agent to check here first.
An empty or stale index sends them straight to rung seven, custom code, for
something that already exists three directories away.

ADR-0014 listed this file as generated and no generator existed, so it would
have stayed empty forever while everyone assumed a tool was maintaining it.
AUDIT-001, finding A001-F06.

Method: parse each package with the ast module, collect public classes,
functions and methods, then resolve call sites by name across the same tree. It
is deliberately name based rather than a full resolver. A name collision
produces an over broad caller list, which is a far cheaper error than a missing
one, because the cost of this index being wrong is a reader who does not find
something that exists.

Usage:
  scripts/docs/build_context_index.py            write context_index.md
  scripts/docs/build_context_index.py --check    fail if it would change
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

#: One public class or function, as the index renders it: kind, name, file,
#: line, doc and package. A plain mapping rather than a dataclass because it is
#: written straight to JSON and read back by the check, and a dataclass would
#: buy a constructor for something with no behaviour.
Symbol = dict[str, Any]

ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "context_index.md"

PACKAGES = (
    "finops_core",
    "finops_providers",
    "finops_ingest",
    "finops_api",
    "finops_mcp",
)

HEADER = """# Context index

<!-- Basic boiler Plate Doc | Grade A
     Why this file exists: The function level index, generated from source. It is rung two
     of the decision ladder, does this already exist here, so it prevents a duplicate
     implementation. Ships empty and fills itself on the first sync.
     Grade A here: nothing in this file is specific to this project. Copy it unchanged.
     Grades: A copy into a new project as is, no edits. B copy it and swap the
     names, paths or patterns named above. C leave behind, it is this project's
     own content rather than scaffolding, and is not tagged.
-->

Every public symbol, where it lives, and what calls it.

**Generated by `make doc-sync`. Do not edit by hand.**

Check this before writing anything new. It is rung two of the ladder in
ADR-0013: does it already exist in this repository. A symbol listed here should
be reused, not reimplemented.

Private symbols, those starting with an underscore, are omitted. Callers are
resolved by name across the same tree, so a name shared by two symbols produces
an over broad caller list. That is deliberate: a reader who checks one extra
call site loses a minute, a reader who misses an existing implementation writes
a duplicate.

"""


#: The four node kinds `ast.get_docstring` accepts. Spelled out rather than
#: taking `ast.AST`, because the wider type compiles and then raises at runtime
#: on any other node.
Documentable = ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef


def first_line(node: Documentable) -> str:
    doc = ast.get_docstring(node) or ""
    line = doc.strip().split("\n", 1)[0].strip()
    return line[:110]


def collect() -> tuple[list[Symbol], dict[str, set[str]]]:
    symbols: list[Symbol] = []
    calls: dict[str, set[str]] = defaultdict(set)

    for package in PACKAGES:
        base = ROOT / package
        if not base.exists():
            continue
        for path in sorted(base.rglob("*.py")):
            rel = path.relative_to(ROOT).as_posix()
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeDecodeError) as exc:
                print(f"WARN: {rel}: {exc}", file=sys.stderr)
                continue

            for node in tree.body:
                if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
                    symbols.append(
                        {
                            "kind": "class",
                            "name": node.name,
                            "file": rel,
                            "line": node.lineno,
                            "doc": first_line(node),
                            "package": package,
                        }
                    )
                    for sub in node.body:
                        if isinstance(
                            sub, (ast.FunctionDef, ast.AsyncFunctionDef)
                        ) and not sub.name.startswith("_"):
                            symbols.append(
                                {
                                    "kind": "method",
                                    "name": f"{node.name}.{sub.name}",
                                    "file": rel,
                                    "line": sub.lineno,
                                    "doc": first_line(sub),
                                    "package": package,
                                }
                            )
                elif isinstance(
                    node, (ast.FunctionDef, ast.AsyncFunctionDef)
                ) and not node.name.startswith("_"):
                    symbols.append(
                        {
                            "kind": "function",
                            "name": node.name,
                            "file": rel,
                            "line": node.lineno,
                            "doc": first_line(node),
                            "package": package,
                        }
                    )

            # A distinct name from the loop above. Reusing `node` bound it to
            # `stmt` there and to `AST` here, which is two types for one name.
            for called in ast.walk(tree):
                if not isinstance(called, ast.Call):
                    continue
                func = called.func
                name = (
                    func.id
                    if isinstance(func, ast.Name)
                    else func.attr
                    if isinstance(func, ast.Attribute)
                    else None
                )
                if name:
                    calls[name].add(rel)

    return symbols, calls


def render(symbols: list[Symbol], calls: dict[str, set[str]]) -> str:
    out = [HEADER]

    if not symbols:
        out.append(
            "No application code exists yet. This file regenerates on the first\n"
            "`make doc-sync` after the first module lands.\n\n"
            "## Reference: the eight ports, once implemented\n\n"
            "Recorded in advance because every other module depends on their shape.\n\n"
            "| Port | Purpose |\n| --- | --- |\n"
            "| `AccountDiscovery` | Enumerate accounts and the organization tree |\n"
            "| `CredentialBroker` | Produce a scoped session for a target account |\n"
            "| `CostExport` | Locate and read billing data |\n"
            "| `MetricSource` | Read time series for a resource |\n"
            "| `ResourceInventory` | Enumerate resources and their relationships |\n"
            "| `QuotaSource` | Read limits and current usage |\n"
            "| `IdentityProvider` | Authenticate a request into a principal |\n"
            "| `EntitlementResolver` | Resolve a principal into a visibility scope |\n"
        )
        return "".join(out)

    by_package: dict[str, list[Symbol]] = defaultdict(list)
    for sym in symbols:
        by_package[sym["package"]].append(sym)

    out.append(f"{len(symbols)} public symbols across {len(by_package)} packages.\n\n")

    for package in PACKAGES:
        rows = by_package.get(package)
        if not rows:
            continue
        out.append(f"## {package}\n\n")
        out.append("| Symbol | Kind | Location | Purpose | Called by |\n")
        out.append("| --- | --- | --- | --- | --- |\n")
        for sym in sorted(rows, key=lambda r: (r["file"], r["line"])):
            leaf = sym["name"].split(".")[-1]
            callers = sorted(calls.get(leaf, set()) - {sym["file"]})
            shown = ", ".join(f"`{c}`" for c in callers[:4])
            if len(callers) > 4:
                shown += f", and {len(callers) - 4} more"
            out.append(
                f"| `{sym['name']}` | {sym['kind']} | "
                f"`{sym['file']}:{sym['line']}` | {sym['doc'] or ''} | "
                f"{shown or 'nothing in this tree'} |\n"
            )
        out.append("\n")

    orphans = [s for s in symbols if not (calls.get(s["name"].split(".")[-1], set()) - {s["file"]})]
    out.append("## Called by nothing in this tree\n\n")
    if not orphans:
        out.append("None.\n")
    else:
        out.append(
            "Each is an entry point, part of a public interface, or dead. "
            "Check each one, and delete what is dead. Rung zero of ADR-0013.\n\n"
        )
        for sym in orphans[:60]:
            out.append(f"- `{sym['name']}` in `{sym['file']}:{sym['line']}`\n")
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    content = render(*collect())
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""

    if args.check:
        if current != content:
            print("FAIL: context_index.md is out of step with the source.")
            print("Run 'make doc-sync'.")
            return 1
        print("OK: context_index.md matches the source")
        return 0

    OUT.write_text(content, encoding="utf-8")
    print("context_index.md regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
